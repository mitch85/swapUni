// Generates supabase/seed.sql from src/data/universities.json.
// Usage: npm run seed:generate
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const universities = JSON.parse(readFileSync(join(root, 'src/data/universities.json'), 'utf8'));

const columns = {
  id: null,
  name: null,
  city: null,
  swapPossible: true,
  ringSwap: 'unknown',
  ringSwapMax: null,
  minSemester: null,
  maxSemester: null,
  modelProgram: false,
  swapWithModel: true,
  swapWithRegular: true,
  regularSwapMinSemester: null,
  requiresExactSemester: false,
  requiresDeanApproval: false,
  excludesLawsuitPlaces: false,
  partnerMustApplyOnline: false,
  allowedTerms: 'both',
  lastSwapTerm: null,
  achievementNote: null,
  deadlineSoSe: null,
  deadlineWiSe: null,
  forms: [],
  contactEmail: null,
  contactPhone: null,
  website: null,
  notes: [],
};

const snake = (key) =>
  ({ deadlineSoSe: 'deadline_sose', deadlineWiSe: 'deadline_wise' })[key] ??
  key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const text = (value) => `'${String(value).replace(/'/g, "''")}'`;

function literal(key, value) {
  if (value === null || value === undefined) return 'null';
  if (key === 'forms') return `${text(JSON.stringify(value))}::jsonb`;
  if (key === 'notes') return value.length ? `array[${value.map(text).join(', ')}]` : `'{}'::text[]`;
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  return text(value);
}

const names = Object.keys(columns);
for (const uni of universities) {
  for (const key of Object.keys(uni)) {
    if (!(key in columns)) throw new Error(`Unknown field "${key}" in ${uni.id}`);
  }
}

const rows = universities.map(
  (uni) => `  (${names.map((key) => literal(key, uni[key] ?? columns[key])).join(', ')})`,
);
const updates = names.filter((n) => n !== 'id').map((n) => `${snake(n)} = excluded.${snake(n)}`);

const sql = `-- Generated by scripts/generate-seed.mjs from src/data/universities.json – do not edit by hand.
-- Source: Übersichtsplan Unis (Stand ${new Date().toISOString().slice(0, 10)}).
insert into public.universities (${names.map(snake).join(', ')}) values
${rows.join(',\n')}
on conflict (id) do update set
  ${updates.join(',\n  ')},
  updated_at = now();
`;

writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log(`Wrote ${universities.length} universities to supabase/seed.sql`);
